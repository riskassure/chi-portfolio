"""Rebuild public map reference data (network required; no credentials used)."""
import json
from pathlib import Path
from urllib.parse import urlencode
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
NATURAL_EARTH = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/'
PARKS = 'https://services1.arcgis.com/fBc8EJBxQRMcHlei/ArcGIS/rest/services/National_Park_Service_Boundaries/FeatureServer/0'
COUNTRIES = {'USA': 'USA', 'TWN': 'Taiwan', 'CHN': 'China', 'VNM': 'Vietnam', 'FRA': 'France', 'CHE': 'Switzerland', 'DEU': 'Germany', 'GBR': 'UK', 'ITA': 'Italy', 'CAN': 'Canada'}


def download(url):
    with urlopen(url, timeout=60) as response:
        return json.load(response)


def build():
    countries = download(NATURAL_EARTH + 'ne_50m_admin_0_countries.geojson')
    states = download(NATURAL_EARTH + 'ne_50m_admin_1_states_provinces.geojson')
    def feature(f, code, name):
        return {'type': 'Feature', 'properties': {'code': code, 'name': name}, 'geometry': f['geometry']}
    all_countries = [feature(f, f['properties']['ADM0_A3'], COUNTRIES.get(f['properties']['ADM0_A3'], f['properties']['ADMIN'])) for f in countries['features']]
    provinces = [feature(f, f['properties']['postal'], 'Quebec' if f['properties']['postal'] == 'QC' else f['properties']['name']) for f in states['features'] if f['properties']['admin'] == 'Canada']
    countries = [f for f in all_countries if f['properties']['code'] in COUNTRIES]
    states = [feature(f, f['properties']['postal'], f['properties']['name']) for f in states['features'] if f['properties']['admin'] == 'United States of America' and f['properties']['postal'] != 'DC']
    query = urlencode({'where': "UNIT_NAME like '%National Park%' OR UNIT_CODE = 'NERI'", 'outFields': 'UNIT_CODE,UNIT_NAME,STATE', 'returnGeometry': 'false', 'returnCentroid': 'true', 'outSR': '4326', 'f': 'json'})
    parks = download(PARKS + '/query?' + query)
    places = []
    for f in parks['features']:
        a = f['attributes']; code = a['UNIT_CODE']
        if a['STATE'] == 'AK' or code in {'WOTR', 'GLAC', 'ISRO', 'VIIS', 'NPSA'}:
            continue
        places.append({'id': 'park-' + code.lower(), 'name': 'New River Gorge National Park and Preserve' if code == 'NERI' else a['UNIT_NAME'], 'kind': 'park', 'longitude': round(f['centroid']['x'], 6), 'latitude': round(f['centroid']['y'], 6), 'url': 'https://www.nps.gov/' + code.lower() + '/'})
    assert len(states) == 50, len(states)
    assert len(countries) == 10, len(countries)
    assert len(provinces) == 13, len(provinces)
    assert len({f['properties']['code'] for f in all_countries}) == len(all_countries)
    assert len(places) == 51, len(places)
    data = {'countries': countries, 'states': states, 'provinces': provinces, 'places': sorted(places, key=lambda p: p['name'])}
    target = ROOT / 'frontend/geography/reference-data.js'
    target.write_text('// Generated by backend/build_travel_reference.py. See docs/features/travel/TRAVEL_MAP.md for sources.\nwindow.TRAVEL_REFERENCE = ' + json.dumps(data, separators=(',', ':')) + ';\n', encoding='utf-8')
    # Four decimals are ample for a generalized 1:50m display layer and keep
    # this file within the existing publication workflow's 2 MiB file limit.
    def rounded(value):
        return [rounded(v) for v in value] if isinstance(value, list) else round(value, 4)
    for f in all_countries:
        f['geometry']['coordinates'] = rounded(f['geometry']['coordinates'])
    world = 'window.TRAVEL_COUNTRIES = ' + json.dumps(all_countries, separators=(',', ':')) + ';\n'
    assert len(world.encode('utf-8')) < 2 * 1024 * 1024
    (target.parent / 'country-reference.js').write_text(world, encoding='utf-8')
    options = {name: sorted([f['properties'] for f in features], key=lambda p: p['name']) for name, features in [('US', states), ('CA', provinces), ('countries', all_countries)]}
    (target.parent / 'region-reference.js').write_text('window.TRAVEL_REGIONS = ' + json.dumps(options, indent=2) + ';\n', encoding='utf-8')
    print(f'Wrote {len(places)} parks, {len(states)} states, {len(provinces)} Canadian provinces/territories, and {len(all_countries)} country/territory outlines.')


if __name__ == '__main__':
    build()
