PICTURE = '\\psset{unit=1cm}\n\\begin{pspicture}(0,0)(2,2)\\psline(0,0)(2,2)\\end{pspicture}'
TREE = '\\pstree{\\Tr{$A$}}{\\Tr{$B$} \\Tr{$C$}}'
FIGURE = '\\begin{figure}\\includegraphics{venn.png}\\end{figure}'
# Shaped like dvisvgm 3 output: glyphs as <path> defs reused through local #links.
SVG = ("<?xml version='1.0' encoding='UTF-8'?>\n<!-- This file was generated by dvisvgm 3.1.2 -->\n"
       "<svg version='1.1' xmlns='http://www.w3.org/2000/svg' xmlns:xlink='http://www.w3.org/1999/xlink' "
       "width='57' height='57' viewBox='0 0 57 57'>\n<defs><clipPath id='c0'><path d='M0 0H57V57H0Z'/></clipPath>"
       "<path id='g0-65' d='M1 2L3 4Z'/></defs>\n<g id='page1' clip-path='url(#c0)'>"
       "<use x='10' y='10' xlink:href='#g0-65'/><path d='M0 0L57 57' stroke='#000' fill='none'/></g>\n</svg>\n")


def svg_for(source):
    """Stand-in renderer: a distinct, valid SVG per diagram source."""
    return SVG.replace('dvisvgm 3.1.2', 'stub ' + hash_pstricks_block(source)).encode()


def create_db(path, tex, rows=()):
    """A math database with one entry, RootedTree (none if tex is None), and diagram rows for rows."""
    with closing(sqlite3.connect(path)) as db:
        db.executescript('''
            CREATE TABLE math_concepts(id INTEGER PRIMARY KEY,canonical_name TEXT,slug TEXT,title TEXT,owner TEXT,cleaned_tex TEXT,is_cleaned INTEGER,rendered_tex TEXT,created_at TEXT,updated_at TEXT);
            CREATE TABLE math_classifications(id INTEGER PRIMARY KEY,code TEXT);
            CREATE TABLE math_types(id INTEGER PRIMARY KEY,type_name TEXT);
            CREATE TABLE math_concept_classifications(concept_id INTEGER,classification_id INTEGER);
            CREATE TABLE math_concept_types(concept_id INTEGER,type_id INTEGER);
            CREATE TABLE math_synonyms(concept_id INTEGER,synonym_text TEXT);
            CREATE TABLE math_definitions(concept_id INTEGER,defined_term TEXT);
            CREATE TABLE math_link_exclusions(concept_id INTEGER,word TEXT);
            CREATE TABLE math_related_concepts(concept_id INTEGER,related_canonical_name TEXT,related_concept_id INTEGER);
            CREATE TABLE math_concept_diagrams(id INTEGER PRIMARY KEY AUTOINCREMENT,concept_id INTEGER NOT NULL,block_index INTEGER NOT NULL,
                source_hash TEXT NOT NULL,source_tex TEXT NOT NULL,svg_path TEXT NOT NULL,created_at TEXT NOT NULL,UNIQUE(concept_id,source_hash));
            INSERT INTO math_classifications VALUES(1,'05C05');
            INSERT INTO math_types VALUES(1,'Definition');
        ''')
        if tex is not None:
            db.execute("INSERT INTO math_concepts VALUES(1,'RootedTree','rooted-tree','rooted tree','chi',?,1,'old','t','t')", (tex,))
            db.execute('INSERT INTO math_concept_classifications VALUES(1,1)')
            db.execute('INSERT INTO math_concept_types VALUES(1,1)')
        for index, source in enumerate(rows, 1):
            name = hash_pstricks_block(source) + '.svg'
            db.execute('INSERT INTO math_concept_diagrams(concept_id,block_index,source_hash,source_tex,svg_path,created_at) '
                       "VALUES(1,?,?,?,?, 't')", (index, hash_pstricks_block(source), source, '/api/math/diagrams/' + name))
        db.commit()


class SvgCheckTests(unittest.TestCase):
    def test_dvisvgm_style_output_accepted(self):
        check_svg(SVG.encode())
        check_svg(SVG.replace('<defs>', "<defs><style>@font-face{src:url(data:font/woff;base64,AAAA)}</style>").encode())

    def test_active_or_external_content_refused(self):
        cases = {
            'script': SVG.replace('<defs>', '<defs><script>alert(1)</script>'),
            'handler': SVG.replace("<g id='page1'", "<g onload='alert(1)' id='page1'"),
            'external link': SVG.replace("xlink:href='#g0-65'", "xlink:href='https://example.com/x.svg#a'"),
            'javascript link': SVG.replace("xlink:href='#g0-65'", "xlink:href='javascript:alert(1)'"),
            'foreignObject': SVG.replace('<defs>', '<defs><foreignObject><p>x</p></foreignObject>'),
            'external style': SVG.replace("clip-path='url(#c0)'", "style='fill:url(https://example.com/a)'"),
            'import': SVG.replace('<defs>', '<defs><style>@import "https://example.com/a.css";</style>'),
            'doctype': SVG.replace('<!--', '<!DOCTYPE svg [<!ENTITY a "b">]><!--'),
            'not svg': SVG.replace('<svg ', '<html ').replace('</svg>', '</html>'),
            'malformed': SVG.replace('</svg>', ''),
            # Chi's case: animation rewrites href to an outside URL after the href check.
            'animated link': SVG.replace('<defs>', '<defs><set href="#i" attributeName="href" to="https://example.com/x"/>'),
            'animated xlink': SVG.replace('<defs>', '<defs><set xlink:href="#g0-65" attributeName="xlink:href" '
                                                   'to="javascript:alert(1)"/>'),
            'animate': SVG.replace('<defs>', '<defs><animate href="#i" attributeName="href" values="https://example.com/x"/>'),
            'animateTransform': SVG.replace('<defs>', '<defs><animateTransform attributeName="transform" type="scale"/>'),
            'animateMotion': SVG.replace('<defs>', '<defs><animateMotion path="M0,0"/>'),
            'discard': SVG.replace('<defs>', '<defs><discard href="#i"/>'),
        }
        for name, text in cases.items():
            with self.subTest(name):
                with self.assertRaises(ValueError):
                    check_svg(text.encode())
        for data in (b'', b'<svg' + b' ' * diagram_sync.SVG_LIMIT, 'not bytes', b'\xff\xfe'):
            with self.assertRaises(ValueError):
                check_svg(data)


