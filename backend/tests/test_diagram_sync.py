class DiagramWorkflowTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.diagrams = self.root / 'diagrams'
        self.diagrams.mkdir()
        self.base = self.root / 'base.db'
        self.renders = []

    def tearDown(self):
        self.temp.cleanup()

    def render(self, source):
        self.renders.append(source)
        return svg_for(source)

    def create(self, path, tex, rows=()):
        create_db(path, tex, rows)

    def working_copy(self, tex=None):
        working = self.root / 'working.db'
        shutil.copyfile(self.base, working)
        if tex is not None:
            with closing(sqlite3.connect(working)) as db:
                db.execute('UPDATE math_concepts SET cleaned_tex=?', (tex,))
                db.commit()
        return working

    def file(self, source):
        return self.diagrams / (hash_pstricks_block(source) + '.svg')

    def test_render_missing_stores_svg_row_and_page_then_is_idempotent(self):
        self.create(self.base, 'A rooted tree:\n' + TREE + '\nEnd.')
        working = self.working_copy()
        summary = render_missing(working, 'RootedTree', self.diagrams, self.render)
        self.assertEqual(summary['rendered'], [self.file(TREE).name])
        self.assertEqual(self.file(TREE).read_bytes(), svg_for(TREE))
        self.assertEqual(list(self.diagrams.iterdir()), [self.file(TREE)])  # No temporary files left.
        with closing(sqlite3.connect(working)) as db:
            rendered = db.execute('SELECT rendered_tex FROM math_concepts').fetchone()[0]
            self.assertEqual(db.execute('SELECT source_tex FROM math_concept_diagrams').fetchall(), [(TREE,)])
        self.assertIn('/api/math/diagrams/' + self.file(TREE).name, rendered)
        self.assertNotIn('Diagram unavailable', rendered)
        again = render_missing(working, 'RootedTree', self.diagrams, self.render)
        self.assertEqual((again['rendered'], again['unchanged']), ([], [self.file(TREE).name]))
        self.assertEqual(len(self.renders), 1)

    def test_render_missing_reuses_valid_files_and_never_replaces_any(self):
        self.create(self.base, PICTURE + ' and ' + TREE)
        working = self.working_copy()
        self.file(PICTURE).write_bytes(SVG.encode())
        summary = render_missing(working, 'RootedTree', self.diagrams, self.render)
        self.assertEqual(summary['reused'], [self.file(PICTURE).name])
        self.assertEqual(self.renders, [TREE])
        self.assertEqual(self.file(PICTURE).read_bytes(), SVG.encode())
        broken = self.root / 'other.db'
        shutil.copyfile(self.base, broken)
        self.file(TREE).write_bytes(b'<svg partial')
        with closing(sqlite3.connect(broken)) as db:
            db.execute('DELETE FROM math_concept_diagrams')
            db.commit()
        with self.assertRaisesRegex(ValueError, 'Remove it'):
            render_missing(broken, 'RootedTree', self.diagrams, self.render)
        self.assertEqual(self.file(TREE).read_bytes(), b'<svg partial')
        with closing(sqlite3.connect(broken)) as db:
            self.assertEqual(db.execute('SELECT count(*) FROM math_concept_diagrams').fetchone()[0], 0)

    def test_render_missing_removes_rows_the_text_no_longer_uses(self):
        self.create(self.base, TREE, rows=[PICTURE])
        working = self.working_copy()
        self.assertEqual(render_missing(working, 'RootedTree', self.diagrams, self.render)['removed_rows'], 1)
        with closing(sqlite3.connect(working)) as db:
            self.assertEqual(db.execute('SELECT source_tex FROM math_concept_diagrams').fetchall(), [(TREE,)])

    def test_missing_svg_entry_becomes_preparable_with_text_unchanged(self):
        self.create(self.base, 'A rooted tree:\n' + TREE)
        working = self.working_copy()
        with self.assertRaisesRegex(ValueError, 'render-missing'):
            build_payload(self.base, working, 'RootedTree', self.diagrams)
        render_missing(working, 'RootedTree', self.diagrams, self.render)
        output = self.root / 'package.zip'
        report = prepare(self.base, working, 'RootedTree', output, self.diagrams)
        self.assertIn('Proposed operation: change existing entry diagrams\n', report)
        self.assertIn('Diagram added: ' + self.file(TREE).name, report)
        payload, files = unpack(output.read_bytes())
        self.assertEqual(files, {hash_pstricks_block(TREE): svg_for(TREE)})
        entry, rows = diagram_intended(payload)
        self.assertEqual(entry, read_snapshot(working)['RootedTree'])
        self.assertEqual(rows, [dict(block_index=1, source_hash=hash_pstricks_block(TREE), source_tex=TREE,
                                     svg_path='/api/math/diagrams/' + self.file(TREE).name)])

    def test_changed_diagram_with_text_and_synonym_edits(self):
        self.create(self.base, 'Old intro. ' + PICTURE + ' ' + FIGURE, rows=[PICTURE])
        self.file(PICTURE).write_bytes(svg_for(PICTURE))
        changed = PICTURE.replace('(2,2)\\end', '(1,2)\\end')
        working = self.working_copy('New intro. ' + changed + ' ' + FIGURE)
        with closing(sqlite3.connect(working)) as db:
            db.execute("INSERT INTO math_synonyms VALUES(1,'arborescence')")
            db.commit()
        render_missing(working, 'RootedTree', self.diagrams, self.render)
        output = self.root / 'package.zip'
        report = prepare(self.base, working, 'RootedTree', output, self.diagrams)
        self.assertIn('Diagram added: ' + self.file(changed).name, report)
        self.assertIn('Diagram row removed: ' + self.file(PICTURE).name, report)
        self.assertIn('+New intro.', report)
        payload, _ = unpack(output.read_bytes())
        self.assertEqual(payload['replacement_synonyms'], ['arborescence'])
        self.assertEqual(payload['expected_diagrams'][0]['source_tex'], PICTURE)
        self.assertEqual(diagram_intended(payload)[0], read_snapshot(working)['RootedTree'])

    def test_other_media_title_and_no_op_changes_refused(self):
        self.create(self.base, PICTURE + ' ' + FIGURE, rows=[PICTURE])
        self.file(PICTURE).write_bytes(svg_for(PICTURE))
        changed = PICTURE.replace('(2,2)\\end', '(1,2)\\end')
        for name, tex, message in [('image changed too', changed + ' ' + FIGURE.replace('venn', 'venn2'), 'Diagram or image changed'),
                                   ('no diagram change', 'Edited. ' + PICTURE + ' ' + FIGURE, 'No diagram change')]:
            with self.subTest(name):
                working = self.working_copy(tex)
                render_missing(working, 'RootedTree', self.diagrams, self.render)
                with self.assertRaisesRegex(ValueError, message):
                    build_payload(self.base, working, 'RootedTree', self.diagrams)
                working.unlink()
        working = self.working_copy(changed + ' ' + FIGURE)
        with closing(sqlite3.connect(working)) as db:
            db.execute("UPDATE math_concepts SET slug='rooted-trees'")
            db.commit()
        render_missing(working, 'RootedTree', self.diagrams, self.render)
        with self.assertRaisesRegex(ValueError, 'slug cannot be changed'):
            build_payload(self.base, working, 'RootedTree', self.diagrams)

    def test_changed_diagram_with_a_title_edit(self):
        self.create(self.base, PICTURE + ' ' + FIGURE, rows=[PICTURE])
        self.file(PICTURE).write_bytes(svg_for(PICTURE))
        working = self.working_copy(PICTURE.replace('(2,2)\\end', '(1,2)\\end') + ' ' + FIGURE)
        with closing(sqlite3.connect(working)) as db:
            db.execute("UPDATE math_concepts SET title='Rooted tree'")
            db.commit()
        render_missing(working, 'RootedTree', self.diagrams, self.render)
        output = self.root / 'package.zip'
        report = prepare(self.base, working, 'RootedTree', output, self.diagrams)
        self.assertIn('Title: "rooted tree" -> "Rooted tree"', report)
        payload, _ = unpack(output.read_bytes())
        self.assertEqual(payload['replacement_title'], 'Rooted tree')
        self.assertNotIn('replacement_synonyms', payload)
        self.assertEqual(diagram_intended(payload)[0], read_snapshot(working)['RootedTree'])

    def test_new_entry_with_diagrams(self):
        self.create(self.base, None)
        working = self.working_copy()
        with closing(sqlite3.connect(working)) as db:
            db.execute("INSERT INTO math_concepts VALUES(1,'RootedTree','rooted-tree','rooted tree','chi',?,1,'','t','t')",
                       ('A tree. ' + TREE,))
            db.execute('INSERT INTO math_concept_classifications VALUES(1,1)')
            db.execute('INSERT INTO math_concept_types VALUES(1,1)')
            db.commit()
        render_missing(working, 'RootedTree', self.diagrams, self.render)
        output = self.root / 'package.zip'
        self.assertIn('add one new entry with diagrams', prepare(self.base, working, 'RootedTree', output, self.diagrams))
        payload, _ = unpack(output.read_bytes())
        self.assertEqual(payload['entry']['cleaned_tex'], 'A tree. ' + TREE)
        with self.assertRaisesRegex(ValueError, 'Media/diagrams'):
            diagram_intended(dict(payload, entry=dict(payload['entry'], cleaned_tex='A tree. ' + TREE + FIGURE)))

    def package(self):
        self.create(self.base, TREE)
        working = self.working_copy()
        render_missing(working, 'RootedTree', self.diagrams, self.render)
        return build_payload(self.base, working, 'RootedTree', self.diagrams)

    def test_tampered_payloads_refused(self):
        payload, files = self.package()
        record = payload['diagrams'][0]
        for name, change in [('hash', dict(record, source_hash='0' * 16)),
                             ('source', dict(record, source_tex=PICTURE)),
                             ('checksum', dict(record, sha256='x')),
                             ('size', dict(record, bytes=0)),
                             ('extra field', dict(record, svg_path='/etc/passwd'))]:
            with self.subTest(name):
                with self.assertRaises(ValueError):
                    diagram_intended(dict(payload, diagrams=[change]))
        with self.assertRaisesRegex(ValueError, 'do not match'):
            diagram_intended(dict(payload, diagrams=[]))
        with self.assertRaises(ValueError):
            diagram_intended(dict(payload, kind='math-entry'))

    def test_unpack_checks_every_file(self):
        payload, files = self.package()
        good = write_package(payload, files, self.root / 'good.zip')
        self.assertEqual(unpack(good)[1], files)
        source_hash = payload['diagrams'][0]['source_hash']
        for name, contents in [('tampered svg', {'svg/' + source_hash + '.svg': svg_for(PICTURE)}),
                               ('extra file', {'svg/' + source_hash + '.svg': files[source_hash], 'run.py': b'x'}),
                               ('missing file', {})]:
            with self.subTest(name):
                buffer = io.BytesIO()
                with zipfile.ZipFile(buffer, 'w') as archive:
                    archive.writestr('diagrams.json', json.dumps(payload))
                    for member, data in contents.items():
                        archive.writestr(member, data)
                with self.assertRaises((ValueError, KeyError)):
                    unpack(buffer.getvalue())


